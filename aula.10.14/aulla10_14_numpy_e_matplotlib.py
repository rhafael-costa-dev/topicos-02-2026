# Import das bibliotecas
import numpy as np
import matplotlib.pyplot as plt

# Criação da lista e do numpy array
dados = [100, 120, 150, 90, 180]
vendas = np.array([100, 120, 150, 90, 180])

# Calculo da média com dados da lista em python
soma = 0
for v in dados:
  soma += v

media = soma / len(dados)
print(media)

print(vendas) # print do array
print(type(vendas)) # print do tipo do objeto array
print(vendas.mean()) # print da média dos dados do array

